import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
import type { OutputAsset, OutputBundle, OutputChunk } from "rollup";
import type { Plugin } from "vite";

function isOutputChunk(value: OutputAsset | OutputChunk): value is OutputChunk {
  return value.type === "chunk";
}

function hashPublicDirectory(hash: ReturnType<typeof createHash>, directory: string, prefix = ""): void {
  for (const entry of readdirSync(directory, { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name))) {
    const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
    const absolutePath = resolve(directory, entry.name);
    if (entry.isDirectory()) hashPublicDirectory(hash, absolutePath, relativePath);
    else if (entry.isFile()) {
      hash.update(relativePath);
      hash.update(readFileSync(absolutePath));
    }
  }
}

export function pwa(): Plugin {
  let publicDirectory = resolve(process.cwd(), "public");
  let indexHtmlPath = resolve(process.cwd(), "index.html");
  return {
    name: "brain-practical-pwa",
    apply: "build",
    configResolved(config) {
      publicDirectory = config.publicDir;
      indexHtmlPath = resolve(config.root, "index.html");
    },
    generateBundle(_options, bundle: OutputBundle) {
      const generatedOutputs = Object.values(bundle)
        .filter(output =>
          isOutputChunk(output)
          || (!isOutputChunk(output) && /\.css$/i.test(output.fileName)),
        );
      // Keep lazy UI code with the active release. Its data still requires the
      // network, but old tabs must not request chunks removed by a new deploy.
      const generatedShellFiles = generatedOutputs.map(output => `./${output.fileName}`).sort();
      const shellFiles = ["./", "./favicon.svg", "./manifest.webmanifest", ...generatedShellFiles];
      const revisionHash = createHash("sha256").update(JSON.stringify(shellFiles)).update(readFileSync(indexHtmlPath));
      for (const output of generatedOutputs.sort((left, right) => left.fileName.localeCompare(right.fileName))) {
        revisionHash.update(output.fileName);
        revisionHash.update(isOutputChunk(output) ? output.code : output.source);
      }
      // Public teaching assets are runtime-cached, not pre-cached. Their bytes still
      // participate in the release id so an updated asset cannot remain stale forever.
      hashPublicDirectory(revisionHash, publicDirectory);
      const entryFiles = Object.values(bundle).filter(output => isOutputChunk(output) && output.isEntry).map(output => `./${output.fileName}`);
      // A worker-only fix must also get a fresh cache namespace.
      revisionHash.update(createServiceWorkerSource("revision", shellFiles, entryFiles));
      const revision = revisionHash.digest("hex").slice(0, 16);
      const workerSource = createServiceWorkerSource(revision, shellFiles, entryFiles);
      this.emitFile({ type: "asset", fileName: "service-worker.js", source: workerSource });
    },
  };
}

export function createServiceWorkerSource(revision: string, shellFiles: string[], entryFiles: string[] = []): string {
  return `/* Generated by build/pwa-vite-plugin.ts. */
const CACHE_PREFIX="brain-practical-navi-";
const SHELL_CACHE=CACHE_PREFIX+"shell-${revision}";
const DATA_CACHE=CACHE_PREFIX+"data-${revision}";
const SHELL_FILES=${JSON.stringify(shellFiles)};
const ENTRY_FILES=${JSON.stringify(entryFiles)};
const STATIC_ASSET=/\\.(?:css|js|mjs|json|svg|png|webp|woff2?|mesh|gz|bin|nii)(?:$|\\?)/i;
const HASHED_BUNDLE=/\\/assets\\/[^/]+-[A-Za-z0-9_-]{8,}\\.[^/]+$/;

function scopeUrl(path="./"){return new URL(path,self.registration.scope).href}
function cacheable(response){return response&&response.ok&&response.type!=="opaque"}
function validAsset(url,response){
  const pathname=new URL(url).pathname;
  const type=(response.headers.get("content-type")||"").split(";")[0].trim().toLowerCase();
  if(/\\.(?:js|mjs)$/.test(pathname))return /^(?:text|application)\\/(?:javascript|ecmascript)$/.test(type);
  if(/\\.css$/.test(pathname))return type==="text/css";
  return !STATIC_ASSET.test(pathname)||type!=="text/html";
}
async function putSafely(cacheName,request,response){
  if(!cacheable(response))return;
  try{const cache=await caches.open(cacheName);await cache.put(request,response.clone())}catch(_error){}
}

self.addEventListener("install",event=>{
  event.waitUntil((async()=>{
    // Each release has its own cache. Verify it fully before activation so a
    // deployment in progress cannot install an HTML fallback as JavaScript.
    const cache=await caches.open(SHELL_CACHE);
    await cache.addAll(SHELL_FILES.map(path=>new Request(scopeUrl(path),{cache:"reload"})));
    for(const path of SHELL_FILES){
      const url=scopeUrl(path),response=await cache.match(url);
      if(!cacheable(response)||!validAsset(url,response))throw new Error("Incomplete app release");
      if(path==="./"){
        const html=await response.text();
        if(!response.headers.get("content-type")?.includes("text/html")||ENTRY_FILES.some(file=>!html.includes(new URL(scopeUrl(file)).pathname)))throw new Error("App shell version mismatch");
      }
    }
  })());
});

self.addEventListener("activate",event=>{
  event.waitUntil((async()=>{
    const names=await caches.keys();
    await Promise.all(names.filter(name=>name.startsWith(CACHE_PREFIX)&&name!==SHELL_CACHE&&name!==DATA_CACHE).map(name=>caches.delete(name)));
    await self.clients.claim();
  })());
});

async function networkFirst(request){
  try{
    const response=await fetch(request);
    await putSafely(SHELL_CACHE,request,response);
    return response;
  }catch(_error){
    const cache=await caches.open(SHELL_CACHE);
    return (await cache.match(request))||(await cache.match(scopeUrl("./")))||Response.error();
  }
}

async function cacheFirst(request,cacheName){
  const cache=await caches.open(cacheName);
  // Pre-cached build files are identical for every requester on this origin.
  // A preview/CDN may add Vary: Origin; module and stylesheet requests then
  // carry different headers from install's Request and must still find them.
  const preCached=cacheName===SHELL_CACHE&&SHELL_FILES.some(path=>scopeUrl(path)===request.url);
  const cached=await cache.match(request,{ignoreVary:preCached});
  if(cached)return cached;
  const response=await fetch(request);
  if(!validAsset(request.url||request,response))return Response.error();
  await putSafely(cacheName,request,response);
  return response;
}

// Keep the app shell paired with this worker's data cache until all of its
// clients close. Serving a newer network shell with older cached labels mixes
// releases. Query strings and hash routes are interpreted by the app itself.
async function releaseNavigation(request){
  const cache=await caches.open(SHELL_CACHE);
  return (await cache.match(scopeUrl("./")))||networkFirst(request);
}

self.addEventListener("fetch",event=>{
  const request=event.request;
  if(request.method!=="GET"||request.headers.has("range"))return;
  const url=new URL(request.url);
  const scope=new URL(self.registration.scope);
  if(url.origin!==scope.origin||!url.pathname.startsWith(scope.pathname)||url.pathname.includes("/cdn-cgi/"))return;
  if(request.mode==="navigate"){
    const appEntry=url.pathname===scope.pathname||url.pathname===scope.pathname+"index.html";
    event.respondWith(appEntry?releaseNavigation(request):networkFirst(request));return;
  }
  if(url.pathname.endsWith("/manifest.webmanifest")){event.respondWith(networkFirst(request));return}
  if(HASHED_BUNDLE.test(url.pathname)){event.respondWith(cacheFirst(request,SHELL_CACHE));return}
  if(STATIC_ASSET.test(url.pathname)){event.respondWith(cacheFirst(request,DATA_CACHE))}
});
`;
}
